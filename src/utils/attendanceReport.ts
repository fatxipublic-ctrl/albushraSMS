import type { AttendanceHistoryEntry, ShiftType } from '../types/sms';
import { buildLiveDateSnapshot } from './liveDate';

export type AttendanceReportPeriod = 'today' | 'yesterday' | 'monthly';

export function filterAttendanceHistory(
  history: AttendanceHistoryEntry[],
  period: AttendanceReportPeriod,
  searchQuery: string,
  shiftFilter: 'All' | ShiftType,
  referenceDate: Date = new Date()
): AttendanceHistoryEntry[] {
  const { todayIso, yesterdayIso, currentMonthIso } =
    buildLiveDateSnapshot(referenceDate);
  const q = searchQuery.trim().toLowerCase();
  return history.filter((entry) => {
    const matchPeriod =
      period === 'monthly'
        ? entry.date.startsWith(currentMonthIso)
        : period === 'yesterday'
          ? entry.date === yesterdayIso
          : entry.date === todayIso;

    const matchShift = shiftFilter === 'All' || entry.shift === shiftFilter;
    const matchQuery =
      !q ||
      entry.studentId.toLowerCase().includes(q) ||
      entry.studentName.toLowerCase().includes(q) ||
      entry.status.toLowerCase().includes(q) ||
      (entry.excuseReason ?? '').toLowerCase().includes(q);

    return matchPeriod && matchShift && matchQuery;
  });
}

function escapeCsvCell(value: string): string {
  if (/[",\n\r]/.test(value)) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

export function buildAttendanceCsv(entries: AttendanceHistoryEntry[]): string {
  const headers = [
    'Date',
    'Student ID',
    'Student Name',
    'Shift',
    'Program',
    'Status',
    'Attendance Reason',
    'Recorded By',
  ];
  const rows = entries.map((e) => [
    e.date,
    e.studentId,
    e.studentName,
    e.shift,
    e.program,
    e.status,
    e.excuseReason || '',
    e.recordedBy,
  ]);
  return [headers, ...rows]
    .map((row) => row.map((cell) => escapeCsvCell(cell)).join(','))
    .join('\n');
}

function escapePdfText(text: string): string {
  return text
    .replace(/[^\x20-\x7E]/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function truncateText(text: string, maxLen: number): string {
  if (text.length <= maxLen) return text;
  return `${text.slice(0, maxLen - 3)}...`;
}

export function buildAttendancePdfBytes(
  entries: AttendanceHistoryEntry[],
  reportTitle: string,
  periodSubtitle: string
): Uint8Array {
  const presentCount = entries.filter((e) => e.status === 'Present').length;
  const excusedCount = entries.filter((e) => e.status === 'Excused').length;
  const absentCount = entries.filter((e) => e.status === 'Absent').length;

  const linesPerPage = 38;
  const pages: string[][] = [];

  for (let i = 0; i < Math.max(1, entries.length); i += linesPerPage) {
    const slice = entries.slice(i, i + linesPerPage);
    const cmds: string[] = [];

    // Header
    cmds.push('BT');
    cmds.push('/F2 14 Tf');
    cmds.push('40 756 Td');
    cmds.push(`(${escapePdfText('ABSMS - Al-Bushra Printing School Management System')}) Tj`);
    cmds.push('0 -18 Td');
    cmds.push('/F2 11 Tf');
    cmds.push(`(${escapePdfText(reportTitle)}) Tj`);
    cmds.push('0 -14 Td');
    cmds.push('/F1 9 Tf');
    cmds.push(
      `(${escapePdfText(
        `${periodSubtitle}  |  Total: ${entries.length}  |  Present: ${presentCount}  |  Excused: ${excusedCount}  |  Absent: ${absentCount}`
      )}) Tj`
    );
    cmds.push('ET');

    // Divider line
    cmds.push('0.8 w 40 712 m 572 712 l S');

    // Table Header
    cmds.push('BT');
    cmds.push('/F2 8.5 Tf');
    cmds.push('40 696 Td');
    cmds.push(
      `(${escapePdfText(
        'Date        Student ID      Student Name         Shift       Status    Reason / Note'
      )}) Tj`
    );
    cmds.push('ET');
    cmds.push('0.4 w 40 690 m 572 690 l S');

    // Rows
    let y = 676;
    if (slice.length === 0) {
      cmds.push('BT /F1 9 Tf 40 676 Td (No attendance records found for this period.) Tj ET');
    } else {
      for (const entry of slice) {
        const dateCol = entry.date.padEnd(11, ' ');
        const idCol = entry.studentId.padEnd(15, ' ');
        const nameCol = truncateText(entry.studentName, 19).padEnd(20, ' ');
        const shiftCol = truncateText(entry.shift.replace(' Shift', ''), 10).padEnd(11, ' ');
        const statusCol = entry.status.padEnd(9, ' ');
        const reasonCol = entry.excuseReason
          ? truncateText(entry.excuseReason, 36)
          : entry.status === 'Excused'
            ? 'No reason provided'
            : '-';

        const rowLine = `${dateCol} ${idCol} ${nameCol} ${shiftCol} ${statusCol} ${reasonCol}`;
        cmds.push(`BT /F1 8 Tf 40 ${y} Td (${escapePdfText(rowLine)}) Tj ET`);
        y -= 15;
      }
    }

    // Footer
    cmds.push(
      `BT /F1 8 Tf 40 28 Td (${escapePdfText(
        `Generated by ABSMS Attendance Module  |  Page ${pages.length + 1}`
      )}) Tj ET`
    );

    pages.push(cmds);
  }

  // Assemble minimal valid PDF 1.4
  const encoder = new TextEncoder();
  const objects: string[] = [];

  // 1: Catalog, 2: Pages, 3: F1 Helvetica, 4: F2 Helvetica-Bold (using Courier for aligned columns!)
  // Using Courier (/F1) & Courier-Bold (/F2) aligns tabular columns cleanly!
  objects.push('1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n');

  const pageObjNums: number[] = [];
  const baseObjNum = 5;
  pages.forEach((_, idx) => {
    pageObjNums.push(baseObjNum + idx * 2);
  });

  objects.push(
    `2 0 obj\n<< /Type /Pages /Kids [${pageObjNums.map((n) => `${n} 0 R`).join(' ')}] /Count ${pages.length} >>\nendobj\n`
  );
  objects.push(
    '3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\nendobj\n'
  );
  objects.push(
    '4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier-Bold >>\nendobj\n'
  );

  pages.forEach((cmds, idx) => {
    const pageNum = baseObjNum + idx * 2;
    const contentNum = pageNum + 1;
    const stream = cmds.join('\n');
    objects.push(
      `${pageNum} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentNum} 0 R >>\nendobj\n`
    );
    objects.push(
      `${contentNum} 0 obj\n<< /Length ${encoder.encode(stream).length} >>\nstream\n${stream}\nendstream\nendobj\n`
    );
  });

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [0];
  for (const obj of objects) {
    offsets.push(encoder.encode(pdf).length);
    pdf += obj;
  }

  const xrefOffset = encoder.encode(pdf).length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (let i = 1; i < offsets.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return encoder.encode(pdf);
}
