import type { StudentFeeProfile } from './feeProfiles';

function escapeCsvCell(value: string): string {
  if (/[",\n\r]/.test(value)) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

export function buildFeeExcelCsv(profiles: StudentFeeProfile[]): string {
  const headers = [
    'Student ID',
    'Student Name',
    'Paid Courses',
    'Unpaid Courses',
    'Payment Method',
    'Fee Amount',
    'Cashier',
    'Paid / Unpaid',
    'Total Paid ($)',
  ];

  const rows = profiles.map((p) => {
    const entry = p.latestEntry;
    const feeDisplay = entry.receivedAmount.trim()
      ? entry.receivedAmount
      : entry.amount > 0
        ? `$${entry.amount}`
        : '';
    return [
      p.studentId,
      p.studentName,
      p.paidCoursesSummary || 'None',
      p.unpaidCoursesSummary || 'None',
      entry.paymentMethod,
      feeDisplay,
      entry.cashier ?? '',
      p.allPaid ? 'Paid' : 'Unpaid',
      String(p.totalPaidAmount),
    ];
  });

  const body = [headers, ...rows]
    .map((row) => row.map((cell) => escapeCsvCell(cell)).join(','))
    .join('\n');

  return `\uFEFF${body}`;
}

function escapePdfText(text: string): string {
  return text
    .replace(/[^\x20-\x7E]/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function truncateText(text: string, maxLen: number): string {
  if (text.length <= maxLen) return text;
  return `${text.slice(0, Math.max(0, maxLen - 3))}...`;
}

export function buildFeePdfBytes(
  profiles: StudentFeeProfile[],
  filterLabel: string
): Uint8Array {
  const paidStudents = profiles.filter((p) => p.allPaid).length;
  const unpaidStudents = profiles.filter((p) => !p.allPaid).length;
  const totalCollected = profiles.reduce((s, p) => s + p.totalPaidAmount, 0);

  const linesPerPage = 28;
  const pages: string[][] = [];

  for (let i = 0; i < Math.max(1, profiles.length); i += linesPerPage) {
    const slice = profiles.slice(i, i + linesPerPage);
    const cmds: string[] = [];

    // Landscape Header (792 x 612)
    cmds.push('BT');
    cmds.push('/F2 14 Tf');
    cmds.push('36 572 Td');
    cmds.push(
      `(${escapePdfText('ABSMS - Student List Payment Fee Report')}) Tj`
    );
    cmds.push('0 -16 Td');
    cmds.push('/F1 9.5 Tf');
    cmds.push(
      `(${escapePdfText(
        `Filter: ${filterLabel}  |  Students: ${profiles.length}  |  Paid: ${paidStudents}  |  Unpaid: ${unpaidStudents}  |  Total Collected: $${totalCollected.toLocaleString()}`
      )}) Tj`
    );
    cmds.push('ET');

    cmds.push('0.8 w 36 544 m 756 544 l S');

    // Table Header
    cmds.push('BT');
    cmds.push('/F2 8 Tf');
    cmds.push('36 530 Td');
    cmds.push(
      `(${escapePdfText(
        'Student ID      Student Name       Paid Courses             Unpaid Courses           Method   Amount    Cashier            Status'
      )}) Tj`
    );
    cmds.push('ET');
    cmds.push('0.4 w 36 524 m 756 524 l S');

    let y = 510;
    if (slice.length === 0) {
      cmds.push(
        'BT /F1 9 Tf 36 510 Td (No student fee records match the selected filter.) Tj ET'
      );
    } else {
      for (const p of slice) {
        const entry = p.latestEntry;
        const idCol = p.studentId.padEnd(15, ' ');
        const nameCol = truncateText(p.studentName, 17).padEnd(18, ' ');
        const paidCol = truncateText(
          p.paidCoursesSummary || '-',
          23
        ).padEnd(24, ' ');
        const unpaidCol = truncateText(
          p.unpaidCoursesSummary || '-',
          23
        ).padEnd(24, ' ');
        const methodCol = entry.paymentMethod.padEnd(8, ' ');
        const feeText = entry.receivedAmount.trim()
          ? entry.receivedAmount
          : entry.amount > 0
            ? `$${entry.amount}`
            : '-';
        const feeCol = truncateText(feeText, 8).padEnd(9, ' ');
        const cashierCol = truncateText(
          entry.cashier?.trim() || '-',
          17
        ).padEnd(18, ' ');
        const statusCol = p.allPaid ? 'Paid' : 'Unpaid';

        const line = `${idCol} ${nameCol} ${paidCol} ${unpaidCol} ${methodCol} ${feeCol} ${cashierCol} ${statusCol}`;
        cmds.push(`BT /F1 7.8 Tf 36 ${y} Td (${escapePdfText(line)}) Tj ET`);
        y -= 16;
      }
    }

    cmds.push(
      `BT /F1 8 Tf 36 26 Td (${escapePdfText(
        `Generated by ABSMS Fees Module  |  Page ${pages.length + 1}`
      )}) Tj ET`
    );

    pages.push(cmds);
  }

  const encoder = new TextEncoder();
  const objects: string[] = [];

  objects.push('1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n');

  const pageObjNums: number[] = [];
  const baseObjNum = 5;
  pages.forEach((_, idx) => {
    pageObjNums.push(baseObjNum + idx * 2);
  });

  objects.push(
    `2 0 obj\n<< /Type /Pages /Kids [${pageObjNums
      .map((n) => `${n} 0 R`)
      .join(' ')}] /Count ${pages.length} >>\nendobj\n`
  );
  objects.push(
    '3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\nendobj\n'
  );
  objects.push(
    '4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier-Bold >>\nendobj\n'
  );

  pages.forEach((cmds, idx) => {
    const pageNum = baseObjNum + idx * 2;
    const contentNum = pageNum + 1;
    const stream = cmds.join('\n');
    objects.push(
      `${pageNum} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 792 612] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentNum} 0 R >>\nendobj\n`
    );
    objects.push(
      `${contentNum} 0 obj\n<< /Length ${encoder.encode(stream).length} >>\nstream\n${stream}\nendstream\nendobj\n`
    );
  });

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [0];
  for (const obj of objects) {
    offsets.push(encoder.encode(pdf).length);
    pdf += obj;
  }

  const xrefOffset = encoder.encode(pdf).length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (let i = 1; i < offsets.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return encoder.encode(pdf);
}
